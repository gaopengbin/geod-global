it('a successful replacement keeps an old source failure in task history without leaving a false project action',async()=>{
  runtimeRequest.mockResolvedValue([project]);
  const old={...jobs[1],id:'old-failed',status:'failed',sha256:null};
  const history=[old,...jobs];
  wrap(<ProjectsLibrary focusedProjectId={project.id}/>,{jobs:history});
  await screen.findByRole('heading',{name:project.name});
  expect(screen.queryByText('Project downloads and processing')).toBeNull();
  expect(history).toHaveLength(3);expect(history[0].status).toBe('failed');
});
